  var LANGS = ["es", "en", "pt-BR", "fr", "it", "de"];
  var CANONICAL = { es: "es", en: "en", pt: "pt-BR", "pt-BR": "pt-BR", fr: "fr", it: "it", de: "de" };

  function detect() {
    var candidates = (navigator.languages || [navigator.language || "en"]);
    for (var i = 0; i < candidates.length; i++) {
      var raw = (candidates[i] || "").toLowerCase();
      if (!raw) continue;
      var base = raw.split("-")[0];
      var hit = CANONICAL[raw] || CANONICAL[base];
      if (hit) return hit;
    }
    return "en";
  }

  var current = "en";

  function t(key, vars) {
    var lang = I18N[current] || I18N.en;
    var str = lang[key];
    if (str == null) str = I18N.en[key];
    if (str == null) return key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.split("{" + k + "}").join(String(vars[k]));
      });
    }
    return str;
  }

  function cat(raw) {
    var map = {
      "action & adventure": "cat.action", shooter: "cat.shooter", "role playing": "cat.rpg",
      "racing & flying": "cat.racing", sports: "cat.sports", "puzzle & trivia": "cat.puzzle",
      family: "cat.family", "family & friends": "cat.family", strategy: "cat.strategy",
      simulation: "cat.simulation", platformer: "cat.platformer", fighting: "cat.fighting",
      "card & board": "cat.card", classics: "cat.classics", "multiplayer online party": "cat.multi",
      "multiplayer online": "cat.multi", music: "cat.music", tools: "cat.tools", other: "cat.other"
    };
    var k = map[(raw || "").toLowerCase()];
    return k ? t(k) : raw;
  }

  function apply(root) {
    var scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    var html = document.documentElement;
    html.lang = current;
  }

  function setLang(lang) {
    current = (LANGS.indexOf(lang) >= 0) ? lang : "en";
    apply();
    try { localStorage.setItem("x4.lang", current); } catch (e) { /* private mode */ }
    document.dispatchEvent(new CustomEvent("x4:lang"));
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem("x4.lang"); } catch (e) { /* ignore */ }
    current = (saved && LANGS.indexOf(saved) >= 0) ? saved : detect();
  }

